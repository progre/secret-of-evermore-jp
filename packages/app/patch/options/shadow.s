// 日本語の字の影を太くする。
// 原版は字の 1 行を描くたび、右へ 1 ドットずらした写し（$10）を影として次の行へ色 2 で書き、
// その後で本体を色 1 で書く（cca642 以降）。影は右下へ 1 ドットずれる。
// 日本語の字だけ、同じ写しをその行にも先に書き、影を右へ 1 ドット太くする。
// 本体が後から上書きするため、本体と重なる点は本体の色になる。

org {hook_shadow}

// A は描く位置までずらした 1 行ぶんのビット列。左の升が上位バイト、右の升が下位バイトになる。
// Y はこの行の左の升の 2bpp データを指し、右の升は Y + $02 × 2 にある。DB は 7f
shadow_shape:
	db $85,$0E		// STA $0e。本体
	LSR
	db $85,$10		// STA $10。影の写し
	SEP #$20
	LDA.l {wide_flag}
	BNE shadow_wide
	REP #$20
	RTL
shadow_wide:
	db $A5,$04		// LDA $04。ウィンドウの描き方
	BIT #$05		// 影を描かない（ビット 0）、色を入れ替える（ビット 2）
	BEQ shadow_row
	REP #$20
	RTL
// 写しの立っている点を色 2 で書く。原版の影の書き方（cca651）と同じ。
// 1 行ごとに呼ばれるため、サブルーチンにせず左右の升へそれぞれ書く
shadow_row:
	db $A5,$11		// LDA $11。左の升の写し
	EOR #$FF
	db $39,$00,$00		// AND $0000,Y
	db $99,$00,$00		// STA $0000,Y
	db $A5,$11		// LDA $11
	db $19,$01,$00		// ORA $0001,Y
	db $99,$01,$00		// STA $0001,Y
	// 右の升は X で指す。X はフックから戻った後の PLX で元に戻る
	REP #$20
	TYA
	CLC
	db $65,$02		// ADC $02
	db $65,$02		// ADC $02
	TAX
	SEP #$20
	db $A5,$10		// LDA $10。右の升の写し
	EOR #$FF
	db $3D,$00,$00		// AND $0000,X
	db $9D,$00,$00		// STA $0000,X
	db $A5,$10		// LDA $10
	db $1D,$01,$00		// ORA $0001,X
	db $9D,$01,$00		// STA $0001,X
	REP #$20
	RTL
warnpc {hook_shadow}+$100

// 影の写しを作る 6 バイト（STA $0e、PLX、LSR、STA $10）。
// PLX は JSL の戻り先より下に積まれているため、フックから戻った後で行う
org $CCA63C
	JSL shadow_shape
	PLX
	NOP
